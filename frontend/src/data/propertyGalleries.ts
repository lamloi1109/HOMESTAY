/**
 * Converts manifest photos to GalleryImage objects with dynamic base URL
 */
function toGalleryImages(photos: CuratedPhoto[], baseUrl: string): GalleryImage[] {
  return photos.map((p) => ({
    id: p.id,
    src: `${baseUrl}/${p.fullPath}`,
    thumbnailSrc: `${baseUrl}/${p.thumbnailPath}`,
    fullSrc: `${baseUrl}/${p.fullPath}`,
    alt: p.alt,
    caption: p.caption,
    width: p.width,
    height: p.height,
    category: p.category,
  }));
}

// Pre-indexed lookup map for O(1) resolution
const SLUG_AND_CODE_INDEX = new Map<string, string>();
for (const [slug, unit] of Object.entries(PROPERTY_UNIT_MANIFESTS)) {
  SLUG_AND_CODE_INDEX.set(slug.toLowerCase(), slug);
  SLUG_AND_CODE_INDEX.set(slug.toUpperCase().replace(/-/g, "."), slug);
  for (const code of unit.codes) {
    SLUG_AND_CODE_INDEX.set(code.toLowerCase(), slug);
    SLUG_AND_CODE_INDEX.set(code.toUpperCase().replace(/[-.]/g, ""), slug);
    SLUG_AND_CODE_INDEX.set(code.toUpperCase(), slug);
  }
}

/**
 * Resolves curated dual-variant gallery by unit code (e.g. L1.29.08, P1.27.10)
 * or URL slug (e.g. landmark-1-29-08, park-1-27-10).
 * Falls back gracefully to empty array if unlisted.
 */
export function getCuratedGallery(unitCodeOrSlugOrId: string | null | undefined): GalleryImage[] {
  if (!unitCodeOrSlugOrId) return [];

  const raw = unitCodeOrSlugOrId.trim();
  const baseUrl = getAssetBaseUrl();

  // Direct match by slug
  if (PROPERTY_UNIT_MANIFESTS[raw]) {
    return toGalleryImages(PROPERTY_UNIT_MANIFESTS[raw].photos, baseUrl);
  }

  // Lookup by normalized key
  const normalizedKey = raw.toLowerCase();
  const matchedSlug = SLUG_AND_CODE_INDEX.get(normalizedKey) ||
    SLUG_AND_CODE_INDEX.get(raw.toUpperCase()) ||
    SLUG_AND_CODE_INDEX.get(raw.toUpperCase().replace(/[-.]/g, ""));

  if (matchedSlug && PROPERTY_UNIT_MANIFESTS[matchedSlug]) {
    return toGalleryImages(PROPERTY_UNIT_MANIFESTS[matchedSlug].photos, baseUrl);
  }

  // Fallback gracefully without errors
  return [];
}

/**
 * Static dictionary for backward compatibility
 */
export const PROPERTY_GALLERIES: Record<string, GalleryImage[]> = {};
for (const [slug, unit] of Object.entries(PROPERTY_UNIT_MANIFESTS)) {
  const images = toGalleryImages(unit.photos, DEFAULT_R2_BASE_URL);
  PROPERTY_GALLERIES[slug] = images;
  for (const code of unit.codes) {
    PROPERTY_GALLERIES[code] = images;
  }
}
