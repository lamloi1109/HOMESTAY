/**
 * Helper to get curated gallery images with fallback
 */
export function getCuratedGallery(unitCodeOrSlugOrId: string): GalleryImage[] {
  if (PROPERTY_GALLERIES[unitCodeOrSlugOrId]) {
    return PROPERTY_GALLERIES[unitCodeOrSlugOrId];
  }
  // Try normalized slug or code match
  const normalized = unitCodeOrSlugOrId.toUpperCase().replace(/-/g, ".");
  if (PROPERTY_GALLERIES[normalized]) {
    return PROPERTY_GALLERIES[normalized];
  }
  return [];
}
